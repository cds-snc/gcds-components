// eslint-disable-next-line no-undef
const fs = require('fs');
const path = require('path');

// ============================================================================
// VERSION BANNER
// ============================================================================
// File names in dist/gcds aren't versioned, so teams hosting their own copy
// (e.g. Canada.ca) can't tell releases apart. Prepend a license banner with
// the package name, version and build date (UTC, ISO 8601) to the main
// distribution files, in the same style as Vue, React and Bootstrap. "/*!"
// tells minifiers (cssnano, terser) to keep it if the file is re-minified.
// Runs before the CSS copy below so the react/vue copies get it too.
//
//   /*!
//    * @gcds-core/components v1.7.0 (2026-11-12)
//    * https://design-system.canada.ca/
//    * (c) Canadian Digital Service – Service numérique canadien
//    * @license MIT
//    */

const pkg = require('../package.json');
const BANNER_FILES = ['./dist/gcds/gcds.css', './dist/gcds/gcds.esm.js'];
// Same copyright holder as LICENSE (and the gcds-tokens/gcds-utility repos)
const COPYRIGHT_HOLDER = 'Canadian Digital Service – Service numérique canadien';
// CSS @charset must stay the very first thing in the file
const CHARSET_PATTERN = /^@charset "[^"]*";\n?/i;

// Matches a banner added by a previous run, so re-running doesn't stack them
const escapedName = pkg.name.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
const BANNER_PATTERN = new RegExp(
  `^/\\*!\\n \\* ${escapedName} v.*\\n(?: \\*.*\\n)*? \\*/\\n`,
);

function buildBanner() {
  const buildDate = new Date().toISOString().slice(0, 10);
  return [
    '/*!',
    ` * ${pkg.name} v${pkg.version} (${buildDate})`,
    ` * ${pkg.homepage}`,
    ` * (c) ${COPYRIGHT_HOLDER}`,
    ` * @license ${pkg.license}`,
    ' */',
    '',
  ].join('\n');
}

const countLines = text => (text.match(/\n/g) || []).length;

function addVersionBanner(filePath, banner) {
  if (!fs.existsSync(filePath)) {
    console.log(`⚠️  ${filePath} not found, skipping version banner`);
    return;
  }

  const original = fs.readFileSync(filePath, 'utf8');
  const charset = original.match(CHARSET_PATTERN)?.[0] || '';
  const content = original.slice(charset.length);
  const oldBanner = content.match(BANNER_PATTERN)?.[0] || '';
  const prefix = charset && !charset.endsWith('\n') ? `${charset}\n` : charset;
  fs.writeFileSync(filePath, prefix + banner + content.slice(oldBanner.length));

  // The banner pushes the code down, so shift the source map to match
  // (each ";" at the start of "mappings" is one empty generated line).
  // Skipped after an @charset line, where the lines aren't at the start.
  const mapPath = `${filePath}.map`;
  const shift = countLines(banner) - countLines(oldBanner);
  if (!charset && shift !== 0 && fs.existsSync(mapPath)) {
    const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
    map.mappings =
      shift > 0 ? ';'.repeat(shift) + map.mappings : map.mappings.slice(-shift);
    fs.writeFileSync(mapPath, JSON.stringify(map));
  }
}

try {
  const banner = buildBanner();
  BANNER_FILES.forEach(file => addVersionBanner(file, banner));
  console.log(`✅ Added version banner:\n${banner}`);
} catch (error) {
  console.error('❌ Error adding version banner:', error.message);
}

// Copy CSS files
fs.copyFileSync('./dist/gcds/gcds.css', '../react/gcds.css');
fs.copyFileSync('./dist/gcds/gcds.css', '../vue/gcds.css');

// ============================================================================
// COMPONENTS.JSON PATH SANITIZATION
// ============================================================================
// Removes personal directory paths from components.json for portability
// Also removes the timestamp to avoid unnecessary changes in git

const COMPONENTS_FILE = '../specs/components.json';

// JSON has no comments, so each generated file starts with a "$comment" key
// describing what it is. Tools that don't know the key ignore it.
const COMPONENTS_COMMENT =
  'Generated by Stencil (docs-json output) and cleaned up by scripts/postbuild.js. Do not edit by hand. ' +
  "Stencil's detailed component docs, used internally by repo scripts. Not published to npm.";
const CEM_COMMENT =
  'Generated by Stencil (docs-custom-elements-manifest output) and scripts/postbuild.js. Do not edit by hand. ' +
  'Custom Elements Manifest (https://github.com/webcomponents/custom-elements-manifest) describing every GCDS component. ' +
  'Source for web-types.json and vscode-data.json, and referenced by "customElements" in package.json.';

// Returns a copy of `data` with "$comment" as the first key
function withComment(comment, data) {
  const result = { $comment: comment };
  Object.entries(data)
    .filter(([key]) => key !== '$comment')
    .forEach(([key, value]) => (result[key] = value));
  return result;
}

const WORKSPACE_ROOT = path.posix.resolve(__dirname, '../..');

// Paths that need sanitization
const PATH_FIELDS = ['filePath', 'dirPath', 'readmePath', 'usagesDir'];

// Sanitize a single path by removing workspace root
function sanitizePath(filePath) {
  return filePath?.split(WORKSPACE_ROOT).at(-1) || filePath;
}

// Sanitize all component paths
function sanitizeComponentPaths(components) {
  components.forEach(component => {
    // Sanitize top-level paths
    PATH_FIELDS.forEach(field => {
      component[field] = sanitizePath(component[field]);
    });

    // Sanitize nested paths in complexType.references
    component.props?.forEach(prop => {
      prop.complexType?.references &&
        Object.values(prop.complexType.references).forEach(ref => {
          ref.path = sanitizePath(ref.path);
        });
    });
  });
}

// Main sanitization function
function sanitizeComponentsFile() {
  const componentsPath = path.join(__dirname, COMPONENTS_FILE);

  if (!fs.existsSync(componentsPath)) {
    console.log('⚠️  components.json not found, skipping sanitization');
    return;
  }

  try {
    const components = JSON.parse(fs.readFileSync(componentsPath, 'utf8'));

    if (!components.components?.length) {
      throw new Error('Invalid components.json structure');
    }

    delete components.timestamp;

    sanitizeComponentPaths(components.components);
    const sanitizedJsonStr = JSON.stringify(
      withComment(COMPONENTS_COMMENT, components),
      null,
      2,
    )
      // normalize eol for Windows
      .replaceAll('\\r', '');

    fs.writeFileSync(componentsPath, sanitizedJsonStr);

    console.log('✅ Paths sanitized and timestamp removed in components.json');
  } catch (error) {
    throw new Error(`Sanitization failed: ${error.message}`);
  }
}

// Sanitize paths in components.json to remove personal directory information
try {
  sanitizeComponentsFile();
} catch (error) {
  console.error('❌ Error sanitizing paths:', error.message);
}

// ============================================================================
// CUSTOM ELEMENTS MANIFEST: FLAG REQUIRED PROPS
// ============================================================================
// The Custom Elements Manifest schema has no "required" field, so IDEs can't
// show which attributes are required. Stencil already knows (props declared
// with `!`), so prefix those descriptions with "(required)" using the
// `required` flag from components.json.

const CEM_FILE = '../specs/custom-elements.json';
const REQUIRED_PREFIX = '(required)';

function markRequiredInManifest() {
  const componentsPath = path.join(__dirname, COMPONENTS_FILE);
  const manifestPath = path.join(__dirname, CEM_FILE);

  if (!fs.existsSync(componentsPath) || !fs.existsSync(manifestPath)) {
    console.log(
      '⚠️  components.json or custom-elements.json not found, skipping',
    );
    return;
  }

  const { components } = JSON.parse(fs.readFileSync(componentsPath, 'utf8'));
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

  // Map of tag name -> Set of required prop names (camelCase)
  const requiredByTag = new Map(
    components.map(component => [
      component.tag,
      new Set(
        component.props.filter(prop => prop.required).map(prop => prop.name),
      ),
    ]),
  );

  const markRequired = item => {
    const description = item.description || '';
    if (!description.startsWith(REQUIRED_PREFIX)) {
      item.description = `${REQUIRED_PREFIX} ${description}`.trim();
    }
  };

  let count = 0;
  manifest.modules.forEach(module => {
    module.declarations?.forEach(declaration => {
      const required = requiredByTag.get(declaration.tagName);
      if (!required?.size) return;

      declaration.attributes?.forEach(attribute => {
        if (required.has(attribute.fieldName)) {
          markRequired(attribute);
          count++;
        }
      });
      declaration.members?.forEach(member => {
        if (member.kind === 'field' && required.has(member.name)) {
          markRequired(member);
        }
      });
    });
  });

  fs.writeFileSync(
    manifestPath,
    JSON.stringify(withComment(CEM_COMMENT, manifest), null, 2),
  );
  console.log(`✅ Marked ${count} required attributes in custom-elements.json`);
}

try {
  markRequiredInManifest();
} catch (error) {
  console.error('❌ Error marking required attributes:', error.message);
}
